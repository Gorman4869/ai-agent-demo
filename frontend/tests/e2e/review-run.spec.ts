import { expect, test } from '@playwright/test'

test('reviews real fixture sources, refreshes approval, publishes and refreshes the same result', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '审查', exact: true }).click()
  await page.getByRole('button', { name: /启动审查/ }).click()
  await expect(page.locator('.connection')).toHaveText('waiting_approval', { timeout: 40_000 })
  await expect(page.locator('.review-result .evidence-card')).toHaveCount(3)
  const runBefore = await page.locator('.facts div').filter({ hasText: 'RUN' }).locator('dd').textContent()
  await page.reload()
  await expect(page.locator('.approval-card')).toContainText('publish_review')
  await expect(page.locator('.review-result .evidence-card')).toHaveCount(3)
  const approvalRequest = page.waitForRequest((request) => request.method() === 'POST' && request.url().includes('/approvals/'))
  await page.getByRole('button', { name: '批准', exact: true }).click()
  expect((await approvalRequest).postDataJSON()).toEqual({ decision: 'approve' })
  await expect(page.locator('.review-result')).toContainText('审查已发布')
  await expect(page.locator('.publication-result')).toContainText('版本 2')
  await page.reload()
  await expect(page.locator('.review-result')).toContainText('审查已发布')
  await expect(page.locator('.facts div').filter({ hasText: 'RUN' }).locator('dd')).toHaveText(runBefore ?? '')
  await expect(page.locator('.facts div').filter({ hasText: 'SOURCES' }).locator('dd')).toHaveText('3')
  await page.screenshot({ path: 'test-results/review/review-published.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.review-result .evidence-card')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/review/review-mobile.png', fullPage: true })
})
